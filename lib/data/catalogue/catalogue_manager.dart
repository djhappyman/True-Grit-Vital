final class _DigestSink implements Sink<Digest> {
  Digest? value;
  @override
  void add(Digest data) {
    value = data;
  }

  @override
  void close() {}
}

Future<String> catalogueFileSha256(File file) async =>
    (await sha256.bind(file.openRead()).first).toString();
String _text(Map<String, dynamic> j, String key, {bool empty = false}) {
  final v = j[key];
  if (v is! String ||
      (!empty && v.trim().isEmpty) ||
      v.length > 2048 ||
      v.contains('\u0000')) {
    throw const FormatException('catalogue_field');
  }
  return v;
}

List<String> _tokens(String value) => RegExp(
  r'[\p{L}\p{N}]+',
  unicode: true,
).allMatches(value.toLowerCase()).map((m) => m.group(0)!).toSet().toList();
void _version(String value) {
  if (!RegExp(r'^[a-zA-Z0-9_-]{1,80}$').hasMatch(value)) {
    throw const FormatException('catalogue_version');
  }
}

void _validate(CatalogueManifest m) {
  _version(m.version);
  final j = m.toJson();
  for (final k in [
    'sourceId',
    'releaseDate',
    'sourceUrl',
    'licence',
    'attribution',
    'admissionReference',
  ]) {
    _text(j, k);
  }
  for (final h in [m.sourceSha256, m.projectionSha256, m.licenceSha256]) {
    if (!RegExp(r'^[a-f0-9]{64}$').hasMatch(h)) {
      throw const FormatException('catalogue_hash');
    }
  }
  if (DateTime.tryParse(m.releaseDate) == null ||
      !Uri.parse(m.sourceUrl).hasScheme ||
      m.recordCount < 1 ||
      m.recordCount > 1000000) {
    throw const FormatException('catalogue_manifest');
  }
}

/// No personal store dependency. Callers must separately clear a source's exact
/// release, retained fields, terms and notices before pinning the SHA-256 of
/// jsonEncode(manifest.toJson()) here. Unknown releases cannot self-admit.
final class CatalogueManager {
  CatalogueManager(
    this.directory, {
    Set<String> admittedManifestSha256 = const {},
    this.allowSynthetic = false,
  }) : admittedManifestSha256 = Set.unmodifiable(admittedManifestSha256);
  final Directory directory;
  final Set<String> admittedManifestSha256;
  final bool allowSynthetic;
  bool _mutating = false;

  // SQLite's OS-backed lock also excludes another manager/isolate/process.
  // It is separate from catalogue artifacts and never touches personal records.
  Future<T> _exclusive<T>(Future<T> Function() action) async {
    if (_mutating) throw StateError('catalogue_update_busy');
    _mutating = true;
    Database? lock;
    var transaction = false;
    try {
      await directory.create(recursive: true);
      final path = '${directory.path}/.update-lock.sqlite';
      if (await FileSystemEntity.type(path, followLinks: false) ==
          FileSystemEntityType.link) {
        throw StateError('catalogue_lock_path');
      }
      lock = sqlite3.open(path);
      lock.execute('PRAGMA busy_timeout=0');
      lock.execute('BEGIN EXCLUSIVE');
      transaction = true;
      final identity = lock
          .select('PRAGMA application_id')
          .single
          .values
          .single;
      if (identity != 0x5643544c) {
        if (identity != 0 ||
            lock.select("SELECT name FROM sqlite_master").isNotEmpty) {
          throw StateError('catalogue_lock_identity');
        }
        lock.execute('PRAGMA application_id=1447253068');
      }
      await _cleanStaging();
      return await action();
    } finally {
      try {
        if (transaction) lock!.execute('COMMIT');
      } finally {
        lock?.close();
        _mutating = false;
      }
    }
  }

  static const _stageOwner = 'vital-catalogue-stage-1';
  Future<Directory> _pending(String purpose) async {
    final pending = await directory.createTemp('.vital-$purpose-');
    await File('${pending.path}/.owner')
        .writeAsString(_stageOwner, flush: true);
    return pending;
  }

  /// Reclaim only marked direct children generated by this version. Legacy,
  /// unmarked and unknown data is preserved. Installed version names cannot
  /// match this prefix; readers pin those installed paths independently.
  Future<void> _cleanStaging() async {
    await for (final entry in directory.list(followLinks: false)) {
      final name = entry.uri.pathSegments.where((s) => s.isNotEmpty).last;
      if (entry is! Directory ||
          !RegExp(r'^\.vital-(stage|activation)-[A-Za-z0-9]+$')
              .hasMatch(name)) {
        continue;
      }
      final marker = File('${entry.path}/.owner');
      if (await FileSystemEntity.type(marker.path, followLinks: false) !=
              FileSystemEntityType.file ||
          await marker.length() != _stageOwner.length ||
          await marker.readAsString() != _stageOwner) {
        continue;
      }
      // Refuse trees containing links or unexpected children. A normal staged
      // build creates only these direct regular files; no recursion is needed.
      const allowed = {
        '.owner',
        'catalogue.sqlite',
        'catalogue.sqlite-journal',
        'NOTICE',
        'manifest.json',
        'pointer',
      };
      final children = await entry
          .list(followLinks: false)
          .take(allowed.length + 1)
          .toList();
      if (children.length > allowed.length) {
        continue;
      }
      if (children.any(
        (child) =>
            child is! File || !allowed.contains(child.uri.pathSegments.last),
      )) {
        continue;
      }
      for (final child in children) {
        if (child.path != marker.path) await child.delete();
      }
      await marker.delete();
      await entry.delete();
    }
  }

  Future<void> recoverStaging() => _exclusive(() async {});

  void _admission(CatalogueManifest m) {
    _validate(m);
    if (m.synthetic
        ? !allowSynthetic
        : !admittedManifestSha256.contains(
            sha256.convert(utf8.encode(jsonEncode(m.toJson()))).toString(),
          )) {
      throw StateError('catalogue_source_not_admitted');
    }
  }

  /// Input is an already-projected JSON-lines file, not arbitrary source XML/ZIP.
  /// Source-specific extraction remains gated until the real source is admitted.
  Future<void> stage({
    required File projection,
    required File licenceNotice,
    required CatalogueManifest manifest,
    bool failBeforePublish = false,
  }) async {
    _admission(manifest);
    return _exclusive(() async {
      final root = directory.path;
      final target = '$root/${manifest.version}';
      if (await Directory(target).exists()) {
        throw StateError('catalogue_version_exists');
      }
      final pending = await _pending('stage');
      try {
        await Isolate.run(
          () => _build(
            projection.path,
            licenceNotice.path,
            pending.path,
            manifest,
          ),
        );
        if (failBeforePublish) throw StateError('injected_stage_failure');
        await pending.rename(target);
      } finally {
        if (await pending.exists()) await pending.delete(recursive: true);
      }
    });
  }

  Future<void> activate(String version, {bool failBeforeCommit = false}) =>
      _exclusive(() async {
        _version(version);
        final reader = await openVersion(version);
        _admission(reader.manifest);
        final pending = await _pending('activation');
        try {
          final pointer = File('${pending.path}/pointer');
          await pointer.writeAsString(version, flush: true);
          if (failBeforeCommit) throw StateError('injected_activation_failure');
          await pointer.rename('${directory.path}/active');
        } finally {
          await pending.delete(recursive: true);
        }
      });
  Future<CatalogueReader?> openActive() async {
    final pointer = File('${directory.path}/active');
    if (!await pointer.exists()) return null;
    if (await pointer.length() > 80) {
      throw const FormatException('catalogue_pointer');
    }
    return openVersion(await pointer.readAsString());
  }

  Future<CatalogueReader> openVersion(String version) async {
    _version(version);
    final path = '${directory.path}/$version';
    final m = await Isolate.run(() async {
      final f = File('$path/manifest.json');
      if (await f.length() > 32768) {
        throw const FormatException('catalogue_manifest_size');
      }
      final json = jsonDecode(await f.readAsString()) as Map<String, dynamic>;
      final manifest = CatalogueManifest.fromJson(json);
      _validate(manifest);
      if (manifest.version != version ||
          json['databaseSha256'] !=
              await catalogueFileSha256(File('$path/catalogue.sqlite')) ||
          manifest.licenceSha256 !=
              await catalogueFileSha256(File('$path/NOTICE'))) {
        throw const FormatException('catalogue_artifact_hash');
      }
      return manifest;
    });
    _admission(m);
    return CatalogueReader._('$path/catalogue.sqlite', m);
  }
}

Future<void> _build(
  String input,
  String notice,
  String target,
  CatalogueManifest m,
) async {
  final projection = File(input);
  if (await projection.length() > 512 * 1024 * 1024 ||
      await File(notice).length() > 1024 * 1024) {
    throw const FormatException('catalogue_input_size');
  }
  if (await catalogueFileSha256(projection) != m.projectionSha256 ||
      await catalogueFileSha256(File(notice)) != m.licenceSha256) {
    throw const FormatException('catalogue_input_hash');
  }
  final db = sqlite3.open('$target/catalogue.sqlite');
  try {
    db.execute('PRAGMA journal_mode=DELETE');
    db.execute(
      'CREATE TABLE product(id INTEGER PRIMARY KEY, code TEXT NOT NULL, concept TEXT NOT NULL, name TEXT NOT NULL, form TEXT NOT NULL, strength TEXT NOT NULL, UNIQUE(concept,code)) STRICT',
    );
    db.execute('CREATE INDEX product_code ON product(code)');
    db.execute(
      'CREATE TABLE token(token TEXT NOT NULL, product INTEGER NOT NULL REFERENCES product(id), PRIMARY KEY(token,product)) WITHOUT ROWID',
    );
    db.execute('BEGIN');
    final insert = db.prepare('INSERT INTO product VALUES (?,?,?,?,?,?)');
    final token = db.prepare('INSERT INTO token VALUES (?,?)');
    var count = 0;
    try {
      // Bound a line before decoding; LineSplitter alone can buffer an unbounded line.
      final line = <int>[];
      Future<void> consume() async {
        if (line.isEmpty) throw const FormatException('catalogue_empty_line');
        final j = jsonDecode(utf8.decode(line)) as Map<String, dynamic>;
        final p = CatalogueProduct(
          code: _text(j, 'code'),
          conceptClass: _text(j, 'conceptClass'),
          name: _text(j, 'name'),
          form: _text(j, 'form', empty: true),
          strength: _text(j, 'strength', empty: true),
        );
        if (++count > m.recordCount) {
          throw const FormatException('catalogue_count');
        }
        final words = _tokens('${p.name} ${p.form} ${p.strength}');
        if (words.isEmpty || words.length > 128) {
          throw const FormatException('catalogue_tokens');
        }
        insert.execute([
          count,
          p.code,
          p.conceptClass,
          p.name,
          p.form,
          p.strength,
        ]);
        for (final word in words) {
          token.execute([word, count]);
        }
        line.clear();
      }

      var byteCount = 0;
      final digestResult = _DigestSink();
      final consumedDigest = sha256.startChunkedConversion(digestResult);
      await for (final chunk in projection.openRead()) {
        consumedDigest.add(chunk);
        byteCount += chunk.length;
        if (byteCount > 512 * 1024 * 1024) {
          throw const FormatException('catalogue_input_size');
        }
        for (final byte in chunk) {
          if (byte == 10) {
            await consume();
          } else {
            line.add(byte);
          }
          if (line.length > 16384) {
            throw const FormatException('catalogue_line_size');
          }
        }
      }
      consumedDigest.close();
      if (digestResult.value.toString() != m.projectionSha256) {
        throw const FormatException('catalogue_consumed_hash');
      }
      if (line.isNotEmpty) await consume();
      if (count != m.recordCount) {
        throw const FormatException('catalogue_count');
      }
      db.execute('COMMIT');
      if (db.select('PRAGMA integrity_check').single.values.single != 'ok' ||
          db.select('PRAGMA foreign_key_check').isNotEmpty) {
        throw const FormatException('catalogue_integrity');
      }
    } finally {
      insert.close();
      token.close();
    }
  } finally {
    db.close();
  }
  await File(notice).copy('$target/NOTICE');
  if (await catalogueFileSha256(projection) != m.projectionSha256 ||
      await catalogueFileSha256(File('$target/NOTICE')) != m.licenceSha256) {
    throw const FormatException('catalogue_input_changed');
  }
  final json = {
    ...m.toJson(),
    'databaseSha256': await catalogueFileSha256(
      File('$target/catalogue.sqlite'),
    ),
    'importer': 'vital-projection-1',
    'builtAt': DateTime.now().toUtc().toIso8601String(),
  };
  await File('$target/manifest.json')
      .writeAsString(jsonEncode(json), flush: true);
}

/// Pins a verified immutable version. New activation never changes this reader.
final class CatalogueReader {
  CatalogueReader._(this.path, this.manifest);
  final String path;
  final CatalogueManifest manifest;
  Future<CatalogueSearchPage> search(String query) async {
    if (query.runes.length > 128) {
      throw const FormatException('catalogue_query_length');
    }
    final tokens = _tokens(query);
    if (tokens.length > 16) {
      throw const FormatException('catalogue_query_tokens');
    }
    final result = await Isolate.run(() => _search(path, query, tokens));
    return CatalogueSearchPage(
      query: query,
      products: result.$1,
      manifest: manifest,
      needsRefinement: result.$2,
    );
  }
}

(List<CatalogueProduct>, bool) _search(
  String path,
  String query,
  List<String> tokens,
) {
  final db = sqlite3.open(path, mode: OpenMode.readOnly);
  try {
    db.execute('PRAGMA query_only=ON');
    final exact = db.select('SELECT * FROM product WHERE code=? LIMIT 51', [
      query.trim(),
    ]);
    List<Row>? smallest;
    var clipped = false;
    for (final t in tokens) {
      final rows = db.select(
        'SELECT product FROM token WHERE token>=? AND token<? LIMIT 513',
        [t, '$t\u{10ffff}'],
      );
      if (smallest == null || rows.length < smallest.length) {
        smallest = rows;
        clipped = rows.length == 513;
      }
    }
    final found = <String, CatalogueProduct>{};
    void add(Row r) {
      final p = CatalogueProduct(
        code: r['code'] as String,
        conceptClass: r['concept'] as String,
        name: r['name'] as String,
        form: r['form'] as String,
        strength: r['strength'] as String,
      );
      found['${p.conceptClass}\u0000${p.code}'] = p;
    }

    for (final r in exact) {
      add(r);
    }
    for (final id in (smallest ?? <Row>[]).take(512)) {
      final r = db.select('SELECT * FROM product WHERE id=?', [
        id['product'],
      ]).single;
      final words = _tokens('${r['name']} ${r['form']} ${r['strength']}');
      if (tokens.every((t) => words.any((w) => w.startsWith(t)))) add(r);
      if (found.length > 50) {
        clipped = true;
        break;
      }
    }
    return (found.values.take(50).toList(), clipped || exact.length > 50);
  } finally {
    db.close();
  }
}

/// Coalesces rapid typing to one running query and one latest pending query.
/// Superseded replies return null, including errors from superseded input.
/// Running bounded native reads finish; they never publish stale UI results.
final class CatalogueSearchSession {
  CatalogueSearchSession(this.reader);
  final CatalogueReader reader;
  int _generation = 0;
  bool _running = false, _closed = false;
  (int, String, Completer<CatalogueSearchPage?>)? _pending;
  Future<CatalogueSearchPage?> search(String query) {
    if (_closed) throw StateError('catalogue_search_closed');
    final request = ++_generation;
    _pending?.$3.complete(null);
    final completer = Completer<CatalogueSearchPage?>();
    _pending = (request, query, completer);
    if (!_running) unawaited(_drain());
    return completer.future;
  }

  Future<void> _drain() async {
    _running = true;
    try {
      while (_pending != null) {
        final (generation, query, reply) = _pending!;
        _pending = null;
        try {
          final page = await reader.search(query);
          reply.complete(!_closed && generation == _generation ? page : null);
        } catch (error, stack) {
          if (!_closed && generation == _generation) {
            reply.completeError(error, stack);
          } else {
            reply.complete(null);
          }
        }
      }
    } finally {
      _running = false;
    }
  }

  void close() {
    _closed = true;
    _generation++;
    _pending?.$3.complete(null);
    _pending = null;
  }
}
